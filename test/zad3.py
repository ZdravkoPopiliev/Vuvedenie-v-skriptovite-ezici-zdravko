def add( i, j):
    sum=0
    while j>0:
        if i%j==0:
            sum+=j
        j-=1
    return sum

a = int(input("Input a:"))
b = int(input("Input b:"))

if(a>b):
    c=a
    a=b
    b=c

izobilni = 0
suvursheni = []

for i in range(a,b):
    j = i//2
    sum = add(i, j)
    if sum==i:
        suvursheni.append(sum)
    elif sum>i:
        izobilni+=1

if len(suvursheni)==0:
    print("suvursheni nqma")
else:
    print(suvursheni)
print("Izobilni:", izobilni)
